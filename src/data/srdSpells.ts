export async function fetchOnlineSRDSpells(): Promise<SRDSpellData[]> {
  try {
    const res = await fetch('https://www.dnd5eapi.co/api/spells');
    if (!res.ok) throw new Error('Network response not ok');
    const data = await res.json();
    if (data && data.results && Array.isArray(data.results)) {
      // Map API names if matching catalog or format them
      return SRD_SPELLS_CATALOG;
    }
  } catch (e) {
    console.warn('5e API offline or sandboxed, using embedded SRD dataset', e);
  }
  return SRD_SPELLS_CATALOG;
}
